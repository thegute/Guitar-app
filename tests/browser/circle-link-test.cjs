// The theory course and the Circle masterclass point at each other and keep the key: a lesson moved to A opens its
// Circle chapter in A, and the chapter's lesson button opens the lesson moved to the Circle's key. node tests/browser/circle-link-test.cjs
const { chromium } = require('playwright')
let bad = 0; const fail = m => { bad++; console.log('  PROBLEM', m) }
;(async () => {
  const b = await chromium.launch()
  const page = await b.newPage({ viewport: { width: 840, height: 757 } })
  const errs = []; page.on('pageerror', e => errs.push(e.message))
  await page.addInitScript(() => { window.__kgTest = true; if (sessionStorage.getItem('s')) return; localStorage.clear(); for (const [k, v] of Object.entries({ 'kg:welcomed': '1', 'kg:psyDefault': '1', 'kg:navHidden': '0', 'kg:studioCockpit': 'false', 'kg:getReady': '0', 'kg:tab2': '"learn"', 'kg:tipsMode': '"off"', 'kg:askBubble': 'false', 'kg:looperBubble': 'false', 'kg:lessonKey:c7-secdom': '-3' })) localStorage.setItem(k, v); sessionStorage.setItem('s', '1') })
  await page.goto('http://localhost:4173/'); await page.waitForSelector('.today-card')
  await page.locator('.subtabs [role=tab]:has-text("Explore")').first().click()
  await page.click('.tool:has-text("Theory")')
  await page.locator('[data-testid=course-lesson-c7-secdom]').click()
  await page.waitForSelector('[data-testid=lesson-to-circle]')
  console.log('lesson button:', await page.locator('[data-testid=lesson-to-circle]').innerText())
  await page.locator('[data-testid=lesson-to-circle]').click()
  await page.waitForTimeout(1500)
  const txt = await page.locator('body').innerText()
  const onKey = await page.locator('.cof-keys .chip.on, .chip.on').allInnerTexts()
  console.log('circle: chapter', /chapter (\d) of 6/i.exec(txt)?.[1], '· key chips on', onKey.join(','))
  if (/chapter (\d) of 6/i.exec(txt)?.[1] !== '5') fail('did not open chapter 5')
  if (!onKey.includes('A')) fail('the Circle is not in A (the lesson was moved down 3 from C)')
  // back: the lesson button keeps the key
  await page.locator('button:has-text("Level 7: Secondary dominants")').first().click()
  await page.waitForSelector('[data-testid=deep-step]')
  const key = await page.locator('[data-testid=key-chip] select, select[data-testid=key-chip]').first().inputValue().catch(() => '')
  const keyTxt = await page.locator('.deep-key').innerText()
  console.log('back in the lesson, key:', key, '|', keyTxt.split('\n')[0])
  const shown = await page.locator('[data-testid=key-chip] select option:checked').innerText()
  console.log('  key menu shows:', shown)
  if (!/^A\b/.test(shown)) fail('the lesson did not open in A')
  if (errs.length) fail('page errors: ' + errs.join(' | '))
  await b.close()
  console.log(bad ? `${bad} problem(s)` : 'circle links: all good')
  process.exit(bad ? 1 : 0)
})()
