// Build 20 in the browser: Ask (built-in planner → a practice session → the session bar), beat maker layers and
// keys, windows tucked into the tray and back, the hand guide under an exercise.
// Run with the preview server on :4173:  node tests/browser/build20-test.cjs
const { chromium } = require('playwright')
const problems = []
const bad = m => { problems.push(m); console.log('  PROBLEM', m) }
;(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || undefined, args: ['--autoplay-policy=no-user-gesture-required', '--use-fake-ui-for-media-stream', '--use-fake-device-for-media-stream'] })
  const ctx = await browser.newContext({ viewport: { width: 412, height: 915 }, hasTouch: true, permissions: ['microphone'] })
  const page = await ctx.newPage()
  const errs = []
  page.on('pageerror', e => errs.push(e.message))
  await page.addInitScript(() => { if (sessionStorage.getItem('s')) return; localStorage.clear(); localStorage.setItem('kg:welcomed', '1'); localStorage.setItem('kg:psyDefault', '1'); localStorage.setItem('kg:getReady', '0'); sessionStorage.setItem('s', '1') })
  await page.goto('http://localhost:4173/')
  await page.waitForSelector('nav.nav')
  // Ask: a practice session from the built-in planner
  await page.locator('.nav-search').click()
  const ph1 = await page.locator('.search-input').getAttribute('placeholder')
  await page.waitForTimeout(3500)
  const ph2 = await page.locator('.search-input').getAttribute('placeholder')
  if (ph1 === ph2) bad('ask: example placeholder does not rotate')
  await page.locator('.search-input').fill('I want to practise triads today in G')
  await page.keyboard.press('Enter')
  await page.waitForSelector('.ask-card', { timeout: 5000 })
  const steps = await page.locator('.ask-card .ask-steps li').count()
  console.log('  ask:', await page.locator('.ask-card b').first().textContent(), steps, 'steps')
  if (steps < 3) bad('ask: session has too few steps')
  await page.locator('.ask-card button:has-text("Start this session")').click()
  await page.waitForSelector('.session-bar', { timeout: 5000 })
  if (!(await page.locator('.ex-browser').count())) bad('session: first step did not open the exercises')
  await page.locator('.session-bar button:has-text("Next")').click()
  await page.waitForTimeout(400)
  console.log('  session step 2:', await page.locator('.session-main b').textContent())
  await page.locator('.session-main').click()
  await page.locator('.session-bar button:has-text("Stop the session")').click()
  if (await page.locator('.session-bar').count()) bad('session: did not stop')
  // hand guide under an exercise
  await page.evaluate(() => { localStorage.setItem('kg:tab2', '"songs"'); localStorage.setItem('kg:sub:songs', '"practice"') })
  await page.reload(); await page.waitForSelector('.ex-browser')
  if (!(await page.locator('.hand-guide .hg-card').count())) bad('hand guide: no hand cards under the exercise')
  // beat maker: a pattern layer, the beat idea assistant, tuck away and back
  await page.evaluate(() => { localStorage.setItem('kg:tab2', '"progressions"'); localStorage.setItem('kg:sub:jam', '"beats"') })
  await page.reload(); await page.waitForSelector('.studio')
  await page.locator('.st-patterns button:has-text("Hi-hat 16ths")').click()
  if (!(await page.locator('[data-win="layers"] .st-layers li').count())) bad('beat: pattern did not add a layer')
  await page.locator('button:has-text("Ideas")').click()
  await page.waitForSelector('.ask-card', { timeout: 5000 })
  console.log('  beat ideas:', await page.locator('.ask-card li').count())
  await page.locator('.search-sheet button:has-text("Close")').click()
  await page.locator('[data-win="keys"] .win-btn[aria-label^="Tuck"]').click()
  await page.locator('.win-chip:has-text("Keyboard")').click()
  if (!(await page.locator('[data-win="keys"]').count())) bad('windows: keyboard did not come back from the tray')
  // Zero to Hero on Learn → Course: place, then start today's routine
  await page.evaluate(() => { localStorage.setItem('kg:tab2', '"learn"'); localStorage.setItem('kg:sub:learn', '"course"') })
  await page.reload(); await page.waitForSelector('.z2h')
  const boxes = page.locator('.z2h-check input')
  for (let i = 0; i < 6; i++) await boxes.nth(i).check()
  await page.locator('.z2h button:has-text("week 5")').click()
  console.log('  zero to hero:', (await page.locator('.z2h h3').textContent()), await page.locator('.z2h .small.muted').first().textContent())
  await page.locator('.z2h-today button:has-text("20 min")').click()
  await page.waitForSelector('.session-bar', { timeout: 5000 })
  console.log('  routine step 1:', await page.locator('.session-main b').textContent())
  if (errs.length) bad('page errors: ' + errs.join(' | '))
  await browser.close()
  console.log(problems.length ? `${problems.length} problem(s)` : 'build 20: all good')
  process.exit(problems.length ? 1 : 0)
})()
